#!/usr/bin/env node
// The latest headlines of CHANGELOG.md "## Release notes" for Home's "What's new in ShareOut"
// card, written to src/pages/home/whats-new-data.ts. Same parser and anchors as the docs site's
// What's new page, so each line links to its own entry there.
//
//   node scripts/gen-whats-new.mjs           write the file
//   node scripts/gen-whats-new.mjs --check   exit 1 when the file is out of date (check:changelog runs it)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = join(APP, '..');
const OUT = join(APP, 'src', 'pages', 'home', 'whats-new-data.ts');
const COUNT = 4;

export async function renderWhatsNew() {
	const lib = await import(pathToFileURL(join(ROOT, 'docs-site', 'src', 'lib', 'release-notes.mjs')).href);
	const days = lib.withAnchors(lib.loadReleaseNotes(ROOT));
	const items = [];
	for (const day of days) {
		for (const e of day.entries) {
			if (items.length < COUNT) items.push({ date: day.date, en: lib.headline(e.en), es: lib.headline(e.es), anchor: e.anchor });
		}
	}
	const body = items.map((i) => `  ${JSON.stringify(i)},`).join('\n');
	return `// Generated by scripts/gen-whats-new.mjs from CHANGELOG.md "## Release notes" — do not edit.
// Run \`npm run build:whats-new\` after adding a release note (check:changelog fails until then).

export interface WhatsNewItem { date: string; en: string; es: string; anchor: string }

export const WHATS_NEW: WhatsNewItem[] = [
${body}
];
`;
}

async function main() {
	const next = await renderWhatsNew();
	let cur = '';
	try { cur = readFileSync(OUT, 'utf8'); } catch { /* first run */ }
	if (process.argv.includes('--check')) {
		if (cur !== next) {
			console.error('whats-new: src/pages/home/whats-new-data.ts is out of date with CHANGELOG.md — run `npm run build:whats-new` in shareout-app and commit it.');
			process.exit(1);
		}
		return;
	}
	if (cur !== next) writeFileSync(OUT, next);
	console.log(`whats-new: ${cur === next ? 'up to date' : 'wrote'} ${OUT.slice(APP.length + 1)}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
