#!/usr/bin/env node
/**
 * Embed OpenAPI + agent-skill discovery artifacts for integrations.sh / GEO.
 * Source of truth: docs-site/src/openapi/shareout.yaml, skills/ShareOutSkill/SKILL.md
 *
 * Output:
 *   src/discovery/openapi.spec.json
 *   src/discovery/openapi.agent.json  (trimmed "agent essentials" — ChatGPT Actions etc.)
 *   src/discovery/agent-skill.generated.ts
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zipSync } from 'fflate';
import { parse } from 'yaml';

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(appRoot, '..');
const outDir = join(appRoot, 'src', 'discovery');

const openapiPath = join(repoRoot, 'docs-site', 'src', 'openapi', 'shareout.yaml');
const skillDir = join(repoRoot, 'skills', 'ShareOutSkill');
const skillPath = join(skillDir, 'SKILL.md');

function walkMd(dir) {
  const files = [];
  for (const entry of readdirSync(dir)) {
    const fullPath = join(dir, entry);
    if (statSync(fullPath).isDirectory()) files.push(...walkMd(fullPath));
    else if (entry.endsWith('.md')) files.push(fullPath);
  }
  return files;
}

function buildSkillZipBytes() {
  const zipEntries = {};
  for (const file of walkMd(skillDir)) {
    zipEntries[relative(skillDir, file)] = readFileSync(file);
  }
  return zipSync(zipEntries);
}

const openapiYaml = readFileSync(openapiPath, 'utf8');
const openapiSpec = parse(openapiYaml);
const skillMd = readFileSync(skillPath, 'utf8');

const skillDigest = `sha256:${createHash('sha256').update(skillMd).digest('hex')}`;
const archiveBytes = buildSkillZipBytes();
const archiveDigest = `sha256:${createHash('sha256').update(archiveBytes).digest('hex')}`;

const descMatch = skillMd.match(/^description:\s*"([^"]+)"/m);
const description = descMatch?.[1]
  ?? 'Publish, update, inspect, and manage ShareOut artifacts.';

// The handful of operations an agent driving ShareOut for a person actually needs.
// Small enough for ChatGPT Custom GPT Actions; derived from the full spec so it can't drift.
const AGENT_OPERATIONS = [
  ['/v1/auth/profile', 'get'],
  ['/v1/workspaces', 'get'],
  ['/v1/publish', 'post'],
  ['/v1/artifacts', 'get'],
  ['/v1/artifacts/{id}', 'get'],
  ['/v1/artifacts/{id}', 'patch'],
  ['/v1/search', 'get'],
  ['/v1/support/tickets', 'post'],
  ['/v1/support/tickets', 'get'],
  ['/v1/support/tickets/{ticketId}', 'get'],
  ['/v1/support/tickets/{ticketId}/message', 'post'],
];

function collectRefs(node, refs) {
  if (Array.isArray(node)) node.forEach((n) => collectRefs(n, refs));
  else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      if (k === '$ref' && typeof v === 'string') refs.add(v);
      else collectRefs(v, refs);
    }
  }
}

function buildAgentSpec(spec) {
  const paths = {};
  for (const [path, method] of AGENT_OPERATIONS) {
    const item = spec.paths[path];
    if (!item?.[method]) throw new Error(`agent spec: ${method.toUpperCase()} ${path} missing from shareout.yaml`);
    paths[path] ??= item.parameters ? { parameters: item.parameters } : {};
    paths[path][method] = item[method];
  }
  const components = { securitySchemes: spec.components.securitySchemes };
  const pending = new Set();
  collectRefs(paths, pending);
  const seen = new Set();
  while (pending.size) {
    const ref = pending.values().next().value;
    pending.delete(ref);
    if (seen.has(ref)) continue;
    seen.add(ref);
    const [, , kind, name] = ref.split('/');
    const def = spec.components[kind][name];
    (components[kind] ??= {})[name] = def;
    collectRefs(def, pending);
  }
  return {
    openapi: spec.openapi,
    info: {
      ...spec.info,
      title: 'ShareOut API (agent essentials)',
      description:
        'The small set of ShareOut calls an AI agent needs to publish pages for a person: ' +
        'check the key, list workspaces, publish, find and update pages, and ask the ' +
        'ShareOut team for help. Errors carry `code`, `hint` and `request_id`; on a 5xx or ' +
        'when stuck, create a support ticket quoting the request_id. Full spec: /openapi.json.',
    },
    servers: spec.servers,
    security: spec.security,
    paths,
    components,
  };
}

const agentSpec = buildAgentSpec(openapiSpec);

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'openapi.spec.json'), JSON.stringify(openapiSpec, null, 2) + '\n');
writeFileSync(join(outDir, 'openapi.agent.json'), JSON.stringify(agentSpec, null, 2) + '\n');

const ts = `// AUTO-GENERATED by scripts/embed-discovery.mjs — do not edit.
export const AGENT_SKILL_NAME = 'shareout' as const;
export const AGENT_SKILL_DESCRIPTION = ${JSON.stringify(description)} as const;
export const AGENT_SKILL_DIGEST = ${JSON.stringify(skillDigest)} as const;
export const AGENT_SKILL_ARCHIVE_DIGEST = ${JSON.stringify(archiveDigest)} as const;
export const AGENT_SKILL_MD = ${JSON.stringify(skillMd)} as const;
`;

writeFileSync(join(outDir, 'agent-skill.generated.ts'), ts);

console.log('Embedded discovery artifacts:');
console.log('  openapi.spec.json', (JSON.stringify(openapiSpec).length / 1024).toFixed(1), 'KB');
console.log('  openapi.agent.json', AGENT_OPERATIONS.length, 'operations');
console.log('  agent-skill.generated.ts skill-md', skillDigest.slice(0, 19) + '…');
console.log('  agent-skill.generated.ts archive', archiveDigest.slice(0, 19) + '…');
