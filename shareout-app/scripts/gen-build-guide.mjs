#!/usr/bin/env node
/**
 * Generates src/build-agent/guide.generated.ts — the slice of ShareOut's own artifact guide
 * (skills/ShareOutSkill/) the page-build agent can read on demand through its read_guide tool.
 *
 * Why embed a subset rather than reuse the /v1/skill bundle at runtime: that bundle is a zip
 * fetched from R2 or the static-assets binding, which costs a fetch + unzip inside every
 * build and does not exist in unit tests. The topics below are the few pages that decide
 * whether a built page passes its checks; each is capped so the Worker bundle stays small.
 * The text keeps its $ORIGIN placeholders; the tool fills them for the instance at runtime.
 *
 * check:bundles regenerates this and fails when the committed copy is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillDir = join(appRoot, '..', 'skills', 'ShareOutSkill');
const outFile = join(appRoot, 'src', 'build-agent', 'guide.generated.ts');

/** Per-topic cap, in characters. A topic over it is cut at a line boundary and says so. */
const TOPIC_MAX_CHARS = 20_000;

const TOPICS = [
  { topic: 'stack', title: 'Stack: what a page can load and how files reference each other', file: 'creating/stack.md' },
  { topic: 'pre-ship', title: 'Pre-ship checklist: the states, accessibility and gotchas to tick before publishing', file: 'creating/pre-ship.md' },
  { topic: 'manifest', title: 'The shareout/manifest block: declaring tables, sources and bindings', file: 'core/html-spec/manifest.md' },
  { topic: 'classes', title: 'The .so- classes and design tokens in /sdk/shareout.css', file: 'modules/ui/classes.md' },
  { topic: 'taste', title: 'Design taste: hierarchy, color, type, spacing', file: 'modules/ui/taste.md' },
  { topic: 'access-policy', title: 'Row-level access policy: each viewer sees only their slice', file: 'core/access-policy.md' },
  { topic: 'table', title: 'sdk.table(): structured records, queries and writes', file: 'sdk/table.md' },
];

const entries = TOPICS.map(({ topic, title, file }) => {
  let text = readFileSync(join(skillDir, file), 'utf8').trim();
  let cut = false;
  if (text.length > TOPIC_MAX_CHARS) {
    text = text.slice(0, text.lastIndexOf('\n', TOPIC_MAX_CHARS)).trimEnd();
    cut = true;
  }
  return { topic, title, source: `skills/ShareOutSkill/${file}`, text: cut ? `${text}\n\n(…cut for size; the full page is ${file} in the ShareOut skill.)` : text };
});

const body = entries
  .map((e) => `  ${JSON.stringify(e.topic)}: { title: ${JSON.stringify(e.title)}, source: ${JSON.stringify(e.source)}, text: ${JSON.stringify(e.text)} },`)
  .join('\n');

writeFileSync(outFile, `// GENERATED by scripts/gen-build-guide.mjs from skills/ShareOutSkill — do not edit by hand.
// Regenerate: npm run build:build-guide (check:bundles fails when stale).

export interface BuildGuideTopic { title: string; source: string; text: string }

export const BUILD_GUIDE: Record<string, BuildGuideTopic> = {
${body}
};
`);
console.log(`gen-build-guide: wrote ${entries.length} topics → ${outFile}`);
