// Embed the vendored official-skill markdown into a generated TS module so the
// Worker can publish them without filesystem access at runtime. Run at predeploy
// (and in check:embeds guard). Source of truth: official-skills/*.md + the registry.
//
// Output: src/official-skills/content.generated.ts — a slug→markdown map plus a
// content hash per skill (the cron re-publishes only when a hash changes).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const appRoot = join(__dirname, '..');
const skillsDir = join(appRoot, 'official-skills');
const outFile = join(appRoot, 'src', 'official-skills', 'content.generated.ts');

// Parse the registry's sourceFile list without importing TS: read the slugs+files
// via a light regex over registry.ts (keeps this a zero-dep .mjs).
const registrySrc = readFileSync(join(appRoot, 'src', 'official-skills', 'registry.ts'), 'utf8');
const entries = [...registrySrc.matchAll(/slug:\s*'([^']+)',\s*\n\s*sourceFile:\s*'([^']+)'/g)]
  .map((m) => ({ slug: m[1], file: m[2] }));

if (entries.length === 0) {
  console.error('embed-official-skills: no registry entries parsed');
  process.exit(1);
}

const parts = [];
for (const { slug, file } of entries) {
  const path = join(skillsDir, file);
  if (!existsSync(path)) {
    console.error(`embed-official-skills: missing source ${file} for slug ${slug}`);
    process.exit(1);
  }
  const md = readFileSync(path, 'utf8');
  const hash = createHash('sha256').update(md).digest('hex').slice(0, 16);
  parts.push({ slug, hash, md });
}

const body = parts
  .map((p) => `  ${JSON.stringify(p.slug)}: { hash: ${JSON.stringify(p.hash)}, markdown: ${JSON.stringify(p.md)} },`)
  .join('\n');

const out = `// GENERATED by scripts/embed-official-skills.mjs — do not edit by hand.
// Source: official-skills/*.md + src/official-skills/registry.ts
export interface OfficialSkillContent { hash: string; markdown: string; }
export const OFFICIAL_SKILL_CONTENT: Record<string, OfficialSkillContent> = {
${body}
};
`;

writeFileSync(outFile, out);
console.log(`embed-official-skills: wrote ${parts.length} skills → ${outFile}`);
