/**
 * The rate-card market of a WhatsApp user, 'Other' when unlisted. Takes the phone number
 * (digits, country code first) or, when the user hides it behind a username, the
 * business-scoped user id, which starts with the ISO country code (`AR.1349…`).
 */
export function whatsappMarket(id: string): string {
  const country = /^([A-Z]{2})\./.exec(id)?.[1];
  if (country) return MARKET_BY_COUNTRY[country] ?? 'Other';
  const digits = id.replace(/\D/g, '');
  for (let len = Math.min(4, digits.length); len > 0; len--) {
    const market = MARKET_BY_PREFIX[digits.slice(0, len)];
    if (market) return market;
  }
  return 'Other';
}

/** List price, in micro-USD, of one service message delivered to this user (phone or user id). */
export function whatsappServiceMicroUsd(id: string): number {
  return SERVICE_MICRO_USD[whatsappMarket(id)] ?? SERVICE_MICRO_USD.Other;
}
